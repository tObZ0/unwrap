"use client";

import { useCallback, useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import * as Tabs from "@radix-ui/react-tabs";
import { ExternalLink, Eye, EyeOff, LoaderCircle, RefreshCw, Share2 } from "lucide-react";
import type { Report, SourceLocation } from "@/lib/analysis/types";
import { DEPTH_LABEL, SEVERITY_LABEL, explorerAddress, formatDate } from "@/lib/format";
import { CopyButton, Notice, Tag, cx } from "@/components/ui";

const SEV_TEXT = { critical: "text-sev-critical", high: "text-sev-high", medium: "text-sev-medium", low: "text-sev-low", info: "text-sev-info" } as const;
import { OverviewTab } from "./overview-tab";
import { FunctionsTab } from "./functions-tab";
import { PermissionsTab } from "./permissions-tab";
import { SecurityTab } from "./security-tab";
import { SourceTab } from "./source-tab";
import { AskTab } from "./ask-tab";

export type TabId = "overview" | "functions" | "permissions" | "security" | "source" | "ask";
const TABS: { id: TabId; label: string }[] = [
  { id: "overview", label: "Overview" },
  { id: "functions", label: "Functions" },
  { id: "permissions", label: "Permissions" },
  { id: "security", label: "Security" },
  { id: "source", label: "Source code" },
  { id: "ask", label: "Ask AI" },
];

export interface Nav {
  goTo: (tab: TabId, opts?: { location?: SourceLocation; query?: string }) => void;
}

export function ReportView(props: { report: Report; visibility?: "public" | "private"; isOwner?: boolean; persistent?: boolean; sample?: boolean }) {
  const { report: r, sample } = props;
  const router = useRouter();
  const [tab, setTab] = useState<TabId>("overview");
  const [sourceTarget, setSourceTarget] = useState<SourceLocation | null>(null);
  const [fnQuery, setFnQuery] = useState("");
  const [visibility, setVisibility] = useState(props.visibility ?? "public");
  const [busy, setBusy] = useState<"refresh" | "visibility" | null>(null);
  const [actionError, setActionError] = useState<string | null>(null);
  const [shared, setShared] = useState(false);

  useEffect(() => {
    const sync = () => {
      const h = window.location.hash.slice(1) as TabId;
      if (TABS.some((t) => t.id === h)) setTab(h);
    };
    const raf = requestAnimationFrame(sync);
    window.addEventListener("hashchange", sync);
    return () => {
      cancelAnimationFrame(raf);
      window.removeEventListener("hashchange", sync);
    };
  }, []);

  const changeTab = useCallback((t: TabId) => {
    setTab(t);
    history.replaceState(null, "", `#${t}`);
  }, []);

  const nav: Nav = {
    goTo: (t, opts) => {
      if (opts?.location) setSourceTarget({ ...opts.location });
      if (opts?.query !== undefined) setFnQuery(opts.query);
      changeTab(t);
      document.getElementById("report-tabs")?.scrollIntoView({ behavior: "smooth", block: "start" });
    },
  };

  async function refresh() {
    setBusy("refresh");
    setActionError(null);
    try {
      const res = await fetch("/api/analyze", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ network: r.network.id, address: r.address, refresh: true, visibility }),
      });
      const body = await res.json().catch(() => null);
      if (!res.ok) throw new Error(body?.error?.message ?? `HTTP ${res.status}`);
      router.push(`/report/${body.id}`);
    } catch (e) {
      setActionError((e as Error).message);
      setBusy(null);
    }
  }

  async function toggleVisibility() {
    const next = visibility === "public" ? "private" : "public";
    setBusy("visibility");
    setActionError(null);
    try {
      const res = await fetch(`/api/reports/${r.id}`, { method: "PATCH", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ visibility: next }) });
      const body = await res.json().catch(() => null);
      if (!res.ok) throw new Error(body?.error?.message ?? `HTTP ${res.status}`);
      setVisibility(next);
    } catch (e) {
      setActionError((e as Error).message);
    } finally {
      setBusy(null);
    }
  }

  async function share() {
    const url = window.location.href.split("#")[0]!;
    try {
      if (navigator.share) await navigator.share({ title: `UNWRAP report: ${r.contractName ?? r.address}`, url });
      else {
        await navigator.clipboard.writeText(url);
        setShared(true);
        setTimeout(() => setShared(false), 1600);
      }
    } catch {
      /* user cancelled */
    }
  }

  const explorer = explorerAddress(r.network.explorerUrl, r.address);
  const counts = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
  for (const f of r.findings) counts[f.severity]++;

  return (
    <div className="mx-auto max-w-[1180px] px-5 py-10">
      {sample && (
        <div className="mb-6">
          <Notice tone="warn" title="Sample report">
            Generated by running UNWRAP against <span className="text-fg">RiskyToken</span>, a deliberately unsafe test contract deployed on a local development chain (anvil).
            The address is a local test address and does not exist on any public network. Everything below is real analyser output.
          </Notice>
        </div>
      )}
      {props.persistent === false && !sample && (
        <div className="mb-6">
          <Notice tone="info" title="Development storage">
            This deployment has no database configured, so reports live in server memory and disappear when the server restarts.
          </Notice>
        </div>
      )}

      {/* Header */}
      <header className="flex flex-col gap-5 border-b border-line pb-7 lg:flex-row lg:items-end lg:justify-between">
        <div className="min-w-0">
          <div className="flex flex-wrap items-center gap-2 text-sm text-fg-2">
            <Tag tone={r.network.id.startsWith("robinhood") ? "accent" : "plain"}>{r.network.name}</Tag>
            <Tag tone={r.depth === "source" ? "accent" : "warn"}>{r.depth === "source" ? "Verified source" : r.verification.verified ? `Verified, ${DEPTH_LABEL[r.depth].toLowerCase()}` : "Unverified, bytecode only"}</Tag>
            {r.proxy.isProxy && <Tag tone="warn">Proxy</Tag>}
            {visibility === "private" && <Tag>Private</Tag>}
          </div>
          <h1 className="font-display mt-3 break-words text-3xl font-bold tracking-tight sm:text-4xl">{r.contractName ?? "Unnamed contract"}</h1>
          <div className="mt-2 flex min-w-0 items-center gap-1">
            <span className="truncate font-mono text-sm text-fg-2">{r.address}</span>
            <CopyButton value={r.address} label="Copy address" />
          </div>
          <p className="mt-1 text-xs text-fg-3">
            Analysed {formatDate(r.createdAt)} at block {r.onchain.blockNumber ?? "unknown"}
          </p>
        </div>
        <div className="flex flex-wrap gap-2">
          {explorer && (
            <a href={explorer} target="_blank" rel="noopener noreferrer" className="inline-flex h-9 items-center gap-1.5 rounded-md border border-line-2 px-3 text-sm hover:bg-card">
              <ExternalLink size={15} aria-hidden /> Open in explorer
            </a>
          )}
          {!sample && (
            <>
              <button type="button" onClick={share} className="inline-flex h-9 items-center gap-1.5 rounded-md border border-line-2 px-3 text-sm hover:bg-card">
                <Share2 size={15} aria-hidden /> {shared ? "Link copied" : "Share report"}
              </button>
              <button type="button" onClick={refresh} disabled={busy !== null} className="inline-flex h-9 items-center gap-1.5 rounded-md border border-line-2 px-3 text-sm hover:bg-card disabled:opacity-60">
                {busy === "refresh" ? <LoaderCircle size={15} className="animate-spin" aria-hidden /> : <RefreshCw size={15} aria-hidden />} Refresh analysis
              </button>
              {props.isOwner && (
                <button type="button" onClick={toggleVisibility} disabled={busy !== null} className="inline-flex h-9 items-center gap-1.5 rounded-md border border-line-2 px-3 text-sm hover:bg-card disabled:opacity-60">
                  {visibility === "public" ? <EyeOff size={15} aria-hidden /> : <Eye size={15} aria-hidden />}
                  {visibility === "public" ? "Make private" : "Make public"}
                </button>
              )}
            </>
          )}
        </div>
      </header>
      {actionError && (
        <div className="mt-4">
          <Notice tone="error">{actionError}</Notice>
        </div>
      )}

      {/* Summary */}
      <section className="grid gap-8 border-b border-line py-8 lg:grid-cols-[minmax(0,1.6fr)_minmax(0,1fr)]" aria-labelledby="sum-h">
        <div className="min-w-0 [overflow-wrap:anywhere]">
          <h2 id="sum-h" className="text-sm text-fg-3">
            Summary
          </h2>
          <ul className="mt-3 space-y-2.5">
            {r.summary.map((s, i) => (
              <li key={i} className={cx("leading-relaxed", i === 0 ? "text-lg text-fg" : "text-fg-2")}>
                {s}
              </li>
            ))}
          </ul>
        </div>
        <div className="min-w-0 space-y-5">
          <div>
            <p className="text-sm text-fg-3">Findings by severity</p>
            <div className="mt-2 grid grid-cols-5 divide-x divide-line overflow-hidden rounded-md border border-line bg-card">
              {(["critical", "high", "medium", "low", "info"] as const).map((sv) => (
                <button key={sv} type="button" onClick={() => nav.goTo("security")} className="px-2 py-3 text-left hover:bg-card-2 sm:px-3" aria-label={`${counts[sv]} ${sv} findings`}>
                  <span className={cx("font-display block text-[1.9rem] font-bold leading-none", counts[sv] === 0 ? "text-fg-3/60" : SEV_TEXT[sv])}>{counts[sv]}</span>
                  <span className="mt-1.5 block text-[12.5px] text-fg-2">{SEVERITY_LABEL[sv]}</span>
                </button>
              ))}
            </div>
            <p className="mt-2 text-xs text-fg-3">Counts are not a score. Read each finding: severity and confidence are reported separately.</p>
          </div>
          <div>
            <p className="text-sm text-fg-3">Data available</p>
            <ul className="mt-2 space-y-1 text-sm">
              {r.steps.map((s) => (
                <li key={s.step} className="flex items-start gap-2">
                  <span
                    className={cx("mt-1.5 size-2 shrink-0 rounded-full", s.status === "ok" ? "bg-accent" : s.status === "partial" ? "bg-sev-medium" : s.status === "failed" ? "bg-sev-critical" : "bg-fg-3")}
                    aria-hidden
                  />
                  <span className="text-fg-2">
                    <span className="text-fg">{s.step}</span> <span className="sr-only">status {s.status}</span>
                  </span>
                </li>
              ))}
            </ul>
          </div>
        </div>
      </section>

      {/* Tabs */}
      <Tabs.Root id="report-tabs" value={tab} onValueChange={(v) => changeTab(v as TabId)} className="scroll-mt-20 pt-6">
        <Tabs.List aria-label="Report sections" className="scrollbar-thin -mx-5 flex gap-1 overflow-x-auto border-b border-line px-5">
          {TABS.map((t) => (
            <Tabs.Trigger
              key={t.id}
              value={t.id}
              className="relative shrink-0 px-3 py-2.5 text-sm text-fg-2 hover:text-fg data-[state=active]:text-fg data-[state=active]:after:absolute data-[state=active]:after:inset-x-2 data-[state=active]:after:-bottom-px data-[state=active]:after:h-0.5 data-[state=active]:font-semibold data-[state=active]:after:bg-fg"
            >
              {t.label}
              {t.id === "security" && r.findings.length > 0 && <span className="ml-1.5 text-xs text-fg-3">{r.findings.length}</span>}
              {t.id === "permissions" && r.permissions.length > 0 && <span className="ml-1.5 text-xs text-fg-3">{r.permissions.length}</span>}
            </Tabs.Trigger>
          ))}
        </Tabs.List>
        <div className="pt-8">
          <Tabs.Content value="overview">
            <OverviewTab r={r} nav={nav} />
          </Tabs.Content>
          <Tabs.Content value="functions">
            <FunctionsTab r={r} nav={nav} query={fnQuery} setQuery={setFnQuery} />
          </Tabs.Content>
          <Tabs.Content value="permissions">
            <PermissionsTab r={r} nav={nav} />
          </Tabs.Content>
          <Tabs.Content value="security">
            <SecurityTab r={r} nav={nav} />
          </Tabs.Content>
          <Tabs.Content value="source">
            <SourceTab r={r} target={sourceTarget} />
          </Tabs.Content>
          <Tabs.Content value="ask">
            <AskTab r={r} nav={nav} sample={Boolean(sample)} />
          </Tabs.Content>
        </div>
      </Tabs.Root>
    </div>
  );
}
